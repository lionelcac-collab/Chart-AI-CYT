// Copies the pure-TS packages into supabase/functions/_shared so Deno edge
// functions use exactly the same code as the app (indicators, consensus…).
// Deno needs explicit extensions: './types' → './types.ts', '@chart-boursafrikia/core' → '../core/index.ts'.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
for (const pkg of ['core', 'data']) {
  const src = join(root, 'packages', pkg, 'src');
  const dst = join(root, 'supabase', 'functions', '_shared', pkg);
  rmSync(dst, { recursive: true, force: true });
  mkdirSync(dst, { recursive: true });
  cpSync(src, dst, { recursive: true });
  for (const f of readdirSync(dst)) {
    if (!f.endsWith('.ts')) continue;
    const p = join(dst, f);
    const code = readFileSync(p, 'utf8')
      .replace(/from '(\.\/[^']+?)(?<!\.ts)'/g, "from '$1.ts'")
      .replace(/from '@chart-boursafrikia\/core'/g, "from '../core/index.ts'");
    writeFileSync(p, `// AUTO-GENERATED by scripts/sync-shared.mjs — edit packages/${pkg}/src instead.\n${code}`);
  }
}
console.log('shared packages synced');
