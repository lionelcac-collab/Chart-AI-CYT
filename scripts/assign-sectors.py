#!/usr/bin/env python3
"""Assign each listed share to a sector from the exchanges' official classifications.

Inputs (pdftotext -layout of the official documents):
  - BRVM Bulletin Officiel de la Cote: sector code printed under each share (TEL, FIN, CD, CB, IND, ENE, SPU).
  - NGX Daily Official List (Equities): sector headings (AGRICULTURE, ..., UTILITIES) and sub-sectors.
BVMAC shares are not classified in its bulletin: mapped from each issuer's public activity (see BVMAC below).
Usage: assign-sectors.py brvm.txt ngx.txt > sectors.sql
"""
import re, sys

BRVM = {'TEL': 'telecom', 'FIN': 'banks', 'CD': 'distribution', 'CB': 'consumer', 'IND': 'industry', 'ENE': 'energy', 'SPU': 'energy'}
NGX = {'AGRICULTURE': 'agri', 'CONGLOMERATES': 'conglomerates', 'CONSTRUCTION/REAL ESTATE': 'real_estate', 'CONSUMER GOODS': 'consumer',
       'FINANCIAL SERVICES': 'banks', 'HEALTHCARE': 'healthcare', 'ICT': 'telecom', 'INDUSTRIAL GOODS': 'industry', 'INVESTMENT': 'investment',
       'NATURAL RESOURCES': 'materials', 'OIL AND GAS': 'oil_gas', 'SERVICES': 'services', 'UTILITIES': 'energy'}
BVMAC = {'BANGE': 'banks', 'BGFIHC': 'banks', 'REGIONALE': 'banks', 'SCGRE': 'insurance', 'SAFACAM': 'agri', 'SOCAPALM': 'agri',
         'SIAT': 'agri', 'SIATGABON': 'agri', 'SEMC': 'consumer'}

def brvm(txt):
    out, lines = {}, txt.splitlines()
    for i, l in enumerate(lines):
        m = re.match(r'^\s{4,12}([A-Z]{4,5})\s{2,}[A-Z]', l)
        if not m:
            continue
        for nxt in lines[i + 1:i + 3]:
            c = re.match(r'^\s*(TEL|FIN|CD|CB|IND|ENE|SPU)\b', nxt)
            if c:
                out.setdefault(m.group(1), BRVM[c.group(1)])
                break
    return out

def ngx(txt):
    out, sector, sub = {}, None, ''
    for l in txt.splitlines():
        h = re.match(r'^ ([A-Z][A-Z &/,-]+?)\s*$', l)
        if h and h.group(1) in NGX:
            sector, sub = h.group(1), ''
            continue
        s = re.match(r'^\s{10,20}([A-Z][a-z][A-Za-z ,&/()-]+?)\s*$', l)
        if s:
            sub = s.group(1)
            continue
        m = re.match(r'^\s{2,4}([A-Z][A-Z0-9]{1,14})\s+[A-Z0-9]', l)
        if m and sector and m.group(1) != 'Symbol':
            code = 'insurance' if sector == 'FINANCIAL SERVICES' and 'nsurance' in sub else NGX[sector]
            out.setdefault(m.group(1), code)
    return out

if __name__ == '__main__':
    b, n = brvm(open(sys.argv[1]).read()), ngx(open(sys.argv[2]).read())
    rows = [('BRVM', t, c) for t, c in b.items()] + [('NGX', t, c) for t, c in n.items()] + [('BVMAC', t, c) for t, c in BVMAC.items()]
    print('-- generated by scripts/assign-sectors.py')
    for mk, t, c in rows:
        print(f"update assets set sector_id = (select id from sectors where code = '{c}') where id = '{mk}:{t}' and sector_id is null;")
    print(f'-- BRVM {len(b)} · NGX {len(n)} · BVMAC {len(BVMAC)}', file=sys.stderr)
